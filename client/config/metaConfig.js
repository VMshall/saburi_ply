/**
 * Get meta configuration for a specific path
 * @param {string} pathname - Current route path
 * @returns {Object} Meta configuration object
 */
export const getMetaConfig = (pathname) => {
  const normalizedPath = pathname !== '/' && pathname.endsWith('/')
    ? pathname.slice(0, -1)
    : pathname;

  // Handle blog details route only (not /blog or /blog/)
  if (normalizedPath.startsWith('/blog/') && normalizedPath !== '/blog') {
    const blogConfig = metaConfig['/blog/:slug'];
    if (!blogConfig) return metaConfig['/blog'] || metaConfig['/'];

    return {
      title: blogConfig.title.replace('{blogTitle}', 'Latest Article'),
      description: blogConfig.description.replace('{blogTopic}', 'plywood industry'),
      keywords: blogConfig.keywords.replace('{blogKeywords}', 'plywood articles')
    };
  }

  return metaConfig[normalizedPath] || metaConfig[pathname] || metaConfig['/'];
};
